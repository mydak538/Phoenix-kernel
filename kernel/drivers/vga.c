#include <vga.h>
#include <io.h>
#include <terminal.h>

static uint8_t* vram = (uint8_t*)0xA0000;
static int in_graphics = 0;
static int screen_w = 320;
static int screen_h = 200;

void vga_init_graphics(void) {
    terminal_prints("VGA: Switching to 320x200x256...\n");
    
    // Переключаем в режим 0x13 (320x200x256)
    __asm__ volatile (
        "mov $0x13, %%ax\n"
        "int $0x10\n"
        : : : "ax"
    );
    
    in_graphics = 1;
    terminal_prints("VGA: Graphics mode enabled\n");
}

void vga_text_mode(void) {
    if (in_graphics) {
        __asm__ volatile (
            "mov $0x03, %%ax\n"
            "int $0x10\n"
            : : : "ax"
        );
        in_graphics = 0;
    }
}

void vga_put_pixel(int x, int y, uint8_t color) {
    if (in_graphics && x >= 0 && x < screen_w && y >= 0 && y < screen_h) {
        vram[y * screen_w + x] = color;
    }
}

void vga_draw_rect(int x, int y, int w, int h, uint8_t color) {
    for (int i = 0; i < w; i++) {
        for (int j = 0; j < h; j++) {
            vga_put_pixel(x + i, y + j, color);
        }
    }
}

void vga_draw_line(int x1, int y1, int x2, int y2, uint8_t color) {
    int dx = x2 - x1;
    int dy = y2 - y1;
    int steps = (dx > dy ? dx : dy);
    if (steps == 0) steps = 1;
    
    float xinc = (float)dx / steps;
    float yinc = (float)dy / steps;
    float x = x1, y = y1;
    
    for (int i = 0; i <= steps; i++) {
        vga_put_pixel((int)x, (int)y, color);
        x += xinc;
        y += yinc;
    }
}

